document.addEventListener('DOMContentLoaded', () => {
    // 1. Language Logic
    const langBtn = document.getElementById('langBtn');
    const langMenu = document.getElementById('langMenu');
    const currentFlag = document.getElementById('currentFlag');

    // Toggle Menu
    if (langBtn && langMenu) {
        langBtn.addEventListener('click', (e) => {
            e.stopPropagation();
            langMenu.classList.toggle('active');
        });
    }

    // Close menu when clicking outside
    document.addEventListener('click', () => {
        if (langMenu) langMenu.classList.remove('active');
    });

    // Handle Language Selection
    document.querySelectorAll('.lang-option').forEach(option => {
        option.addEventListener('click', () => {
            const selectedLang = option.getAttribute('data-lang');
            const selectedFlag = option.querySelector('.flag')?.innerText;

            if (currentFlag && selectedFlag) currentFlag.innerText = selectedFlag;
            changeLanguage(selectedLang);
        });
    });

    // 2. Mobile Menu Logic (index/about)
    const burger = document.getElementById('burger');
    const drawer = document.getElementById('mobileDrawer');
    if (burger && drawer) {
        burger.addEventListener('click', () => {
            drawer.classList.toggle('open');
            burger.innerHTML = drawer.classList.contains('open')
                ? '<i class="fas fa-times"></i>'
                : '<i class="fas fa-bars"></i>';
        });
    }

    // 3. Carousel Logic
    const carousel = document.querySelector('.hero-carousel');
    if (carousel) {
        const indicators = document.querySelectorAll('.carousel-indicators .indicator');
        const inner = document.querySelector('.carousel-inner');
        let currentIndex = 0;
        let slideInterval;

        // Update indicators
        function updateIndicators(index) {
            indicators.forEach((indicator, i) => {
                if (i === index) {
                    indicator.classList.add('active');
                } else {
                    indicator.classList.remove('active');
                }
            });
        }

        // Go to slide
        function goToSlide(index) {
            currentIndex = index;
            inner.style.transition = 'transform 0.5s ease-in-out';
            inner.style.transform = `translateX(-${index * 33.333}%)`;
            updateIndicators(index);
        }

        // Start auto slide
        function startAutoSlide() {
            // Clear any existing interval first
            if (slideInterval) {
                clearInterval(slideInterval);
            }
            
            slideInterval = setInterval(() => {
                const nextIndex = (currentIndex + 1) % 3;
                goToSlide(nextIndex);
            }, 3000);
        }

        // Stop auto slide
        function stopAutoSlide() {
            if (slideInterval) {
                clearInterval(slideInterval);
                slideInterval = null;
            }
        }

        // Add indicator click events
        indicators.forEach((indicator, index) => {
            indicator.addEventListener('click', () => {
                stopAutoSlide();
                goToSlide(index);
                startAutoSlide();
            });
        });

        // Initialize carousel
        goToSlide(0);
        // Start auto slide after a short delay
        setTimeout(startAutoSlide, 1000);

        // Pause on hover
        carousel.addEventListener('mouseenter', stopAutoSlide);
        carousel.addEventListener('mouseleave', startAutoSlide);
    }
});

function changeLanguage(lang) {
    const data = translations[lang];
    if (!data) return;

    document.querySelectorAll('[data-i18n]').forEach(element => {
        const key = element.getAttribute('data-i18n');
        if (data[key]) element.innerText = data[key];
    });
}

